/**
 * Turn the Lands Department's 3D Pedestrian Network for Stanley (from CSDI, saved by
 * scripts/csdi-console.js style fetch as content/csdi-pedestrian-stanley.json) into src/stanley-ped.ts.
 *
 *   node --experimental-strip-types --no-warnings scripts/import-pedestrian.ts
 *
 * The file's points are metres east and south of 22.2235 N, 114.2045 E. They are moved to the
 * game's origin, then the script tries every shift up to ±12 m and keeps the one where the network
 * lies best on the game's mapped footways and roads (the survey and OpenStreetMap differ by a few
 * metres here, as the building outlines did).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { OSM } from '../src/stanley-osm.ts';

type Data = {
  KX: number; KY: number; keys: string[]; names: string[];
  dom: { type: Record<string, string>; loc: Record<string, string>; cross: Record<string, string>; weather: Record<string, string> };
  f: Array<[string | string[], number?, number?, number | null?, number | null?, number | null?, number | null?, number | null?]>;
};
const d: Data = JSON.parse(readFileSync(new URL('../content/csdi-pedestrian-stanley.json', import.meta.url), 'utf8'));
const [lat0, lon0] = OSM.origin;
const dx0 = (lon0 - 114.2045) * d.KX, dy0 = (22.2235 - lat0) * d.KY;

// decode: first point absolute, then deltas; move to the game's origin
const decode = (s: string): number[] => {
  const v = s.split(' ').map(Number), out: number[] = [];
  let x = 0, y = 0;
  for (let i = 0; i + 1 < v.length; i += 2) { x += v[i]; y += v[i + 1]; out.push(x - dx0, y - dy0); }
  return out;
};
type Seg = { p: number[]; type: string; loc: string; name: string; cross: string; covered: boolean; street: string };
const segs: Seg[] = [];
for (const r of d.f) {
  const paths = Array.isArray(r[0]) ? r[0] : [r[0]];
  for (const s of paths) {
    segs.push({
      p: decode(s), loc: d.dom.loc[String(r[1])] ?? '', type: d.dom.type[String(r[2])] ?? '',
      name: r[3] != null ? d.names[r[3]] : '', cross: r[4] != null ? d.dom.cross[String(r[4])] : '',
      covered: r[5] === 1, street: r[7] != null ? d.names[r[7]] : '',
    });
  }
}

// line up: rasterise the game's mapped footways and roads, then score each shift by how many
// half-metre samples along the outdoor network land within a metre of them
const W = OSM.w, H = OSM.h;
const walk = new Uint8Array(W * H);
for (const [p, h] of OSM.roads) {
  if (!h) continue;
  for (let i = 0; i + 3 < p.length; i += 2) {
    const len = Math.hypot(p[i + 2] - p[i], p[i + 3] - p[i + 1]);
    for (let t = 0; t <= len; t += 0.5) {
      const x = Math.round(p[i] + ((p[i + 2] - p[i]) * t) / (len || 1)), y = Math.round(p[i + 1] + ((p[i + 3] - p[i + 1]) * t) / (len || 1));
      for (let oy = -1; oy <= 1; oy += 1) for (let ox = -1; ox <= 1; ox += 1) {
        const X = x + ox, Y = y + oy;
        if (X >= 0 && Y >= 0 && X < W && Y < H) walk[Y * W + X] = 1;
      }
    }
  }
}
const samples: number[] = [];
for (const s of segs) {
  if (s.loc !== 'Outdoor') continue;
  for (let i = 0; i + 3 < s.p.length; i += 2) {
    const len = Math.hypot(s.p[i + 2] - s.p[i], s.p[i + 3] - s.p[i + 1]);
    for (let t = 0; t <= len; t += 2) samples.push(s.p[i] + ((s.p[i + 2] - s.p[i]) * t) / (len || 1), s.p[i + 1] + ((s.p[i + 3] - s.p[i + 1]) * t) / (len || 1));
  }
}
let best = { sx: 0, sy: 0, hit: -1 };
for (let sy = -12; sy <= 12; sy += 0.5) for (let sx = -12; sx <= 12; sx += 0.5) {
  let hit = 0;
  for (let i = 0; i < samples.length; i += 2) {
    const x = Math.round(samples[i] + sx), y = Math.round(samples[i + 1] + sy);
    if (x >= 0 && y >= 0 && x < W && y < H && walk[y * W + x]) hit += 1;
  }
  if (hit > best.hit) best = { sx, sy, hit };
}
console.log(`shift ${best.sx} m east, ${best.sy} m south: ${best.hit} of ${samples.length / 2} samples on a mapped way`);

// keep what is on the map, rounded to a tenth of a metre
const r1 = (v: number): number => Math.round(v * 10) / 10;
const out = segs.map((s) => ({ ...s, p: s.p.map((v, i) => r1(v + (i % 2 ? best.sy : best.sx))) }))
  .filter((s) => s.p.some((v, i) => (i % 2 ? v >= -5 && v <= H + 5 : v >= -5 && v <= W + 5)));
const types = [...new Set(out.map((s) => s.type))];
const names = [...new Set(out.map((s) => s.name).concat(out.map((s) => s.street)))].filter(Boolean);
const rows = out.map((s) => [s.p, types.indexOf(s.type), s.loc === 'Indoor' ? 1 : 0, s.name ? names.indexOf(s.name) : -1, s.cross ? 1 : 0, s.covered ? 1 : 0, s.street ? names.indexOf(s.street) : -1]);
const json = JSON.stringify({ types, names, rows });
if (json.includes('`') || json.includes('${')) throw new Error('unexpected characters in data');
writeFileSync(new URL('../src/stanley-ped.ts', import.meta.url), `/**
 * GENERATED by scripts/import-pedestrian.ts from content/csdi-pedestrian-stanley.json.
 * Source: Lands Department, HKSAR Government, 3D Pedestrian Network (portal.csdi.gov.hk).
 * Game metres from the map's top-left corner, shifted ${best.sx} m east and ${best.sy} m south to lie on OSM's ways.
 */
type Raw = { types: string[]; names: string[]; rows: Array<[number[], number, number, number, number, number, number]> };
const RAW: Raw = JSON.parse(String.raw\`${json}\`);
export type PedWay = { p: number[]; type: string; indoor: boolean; name: string; crossesRoad: boolean; covered: boolean; street: string };
export const PED: PedWay[] = RAW.rows.map(([p, t, indoor, n, cross, cov, st]) => ({
  p, type: RAW.types[t], indoor: indoor === 1, name: n >= 0 ? RAW.names[n] : '', crossesRoad: cross === 1, covered: cov === 1, street: st >= 0 ? RAW.names[st] : '',
}));
`);
console.log(`stanley-ped.ts: ${out.length} ways, ${json.length} bytes`);
