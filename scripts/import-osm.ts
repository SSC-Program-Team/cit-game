/**
 * Turn a Stanley OSM export (made in the browser from the OpenStreetMap map API, see
 * docs/design/stanley-expansion.md §2) into src/stanley-osm.ts.
 *
 *   node --experimental-strip-types scripts/import-osm.ts path/to/stanley-osm-1m.json
 *
 * All coordinates are whole metres from the map's top-left corner, y growing south.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('usage: import-osm.ts stanley-osm-1m.json'); process.exit(1); }
const data = JSON.parse(readFileSync(file, 'utf8'));
for (const k of ['buildings', 'roads', 'areas', 'coast', 'walls', 'pois']) {
  if (!Array.isArray(data[k])) { console.error(`missing ${k}`); process.exit(1); }
}
const json = JSON.stringify(data);
if (json.includes('`') || json.includes('${')) { console.error('unexpected characters in data'); process.exit(1); }
writeFileSync(new URL('../src/stanley-osm.ts', import.meta.url), `/**
 * GENERATED by scripts/import-osm.ts. Stanley from OpenStreetMap: © OpenStreetMap contributors,
 * available under the Open Database Licence (openstreetmap.org/copyright).
 * Whole metres from the map's top-left corner (${data.origin?.join(', ')}), y growing south.
 */
import type { OsmData } from './osm-types.ts';

export const OSM: OsmData = JSON.parse(String.raw\`${json}\`);
`);
console.log(`stanley-osm.ts: ${data.buildings.length} buildings, ${data.roads.length} roads, ${data.areas.length} areas, ${json.length} bytes`);
