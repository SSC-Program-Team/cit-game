/**
 * Import a teacher's question bank from CSV into the game.
 *
 *   npm run import -- content/my-bank.csv
 *
 * Writes src/questions-imported.ts (generated; the game merges it into the bank), then
 * `npm run check` validates everything. See content/question-bank-template.csv for the columns:
 *
 *   id, form, topic, question, a, b, c, d, answer, explanation
 *
 * - id: optional; generated from the row number if blank
 * - form: 1-6 (F1-F3 are junior, F4-F6 are DSE)
 * - topic: a code (J1 J2 J3 J4 for junior; A B C D E for DSE) or its name, e.g. "Internet and its applications"
 * - answer: A, B, C or D
 * - question / explanation: use \n for a line break; start a line with spaces to keep code indented
 *
 * Curly quotes, long dashes and ellipses are straightened automatically. Anything else the pixel
 * font cannot draw (e.g. Chinese characters) is reported as an error rather than imported.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { TOPIC_NAMES, type Topic } from '../src/questions.ts';
import { FONT_CHARS } from '../src/font.ts';

const file = process.argv[2];
if (!file) {
  console.error('usage: npm run import -- path/to/bank.csv');
  process.exit(1);
}

/** RFC 4180-ish: quoted fields, doubled quotes, commas and newlines inside quotes */
function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.some((f) => f.trim())) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((f) => f.trim())) rows.push(row);
  return rows;
}

const clean = (s: string): string => s
  .replace(/^﻿/, '')
  .replace(/[‘’‛′]/g, "'")
  .replace(/[“”‟″]/g, '"')
  .replace(/[–—−]/g, '-')
  .replace(/…/g, '...')
  .replace(/ /g, ' ')
  .replace(/×/g, 'x')
  .replace(/\\n/g, '\n')
  .replace(/[ \t]+$/gm, '')
  .trim();

const rows = parseCsv(readFileSync(file, 'utf8'));
const header = rows.shift()?.map((h) => clean(h).toLowerCase());
const need = ['form', 'topic', 'question', 'a', 'b', 'c', 'd', 'answer', 'explanation'];
if (!header || need.some((h) => !header.includes(h))) {
  console.error(`header must include: id (optional), ${need.join(', ')}`);
  process.exit(1);
}
const col = (r: string[], name: string): string => clean(r[header.indexOf(name)] ?? '');

const byName = new Map<string, Topic>();
for (const [code, name] of Object.entries(TOPIC_NAMES)) {
  byName.set(code.toLowerCase(), code as Topic);
  byName.set(name.toLowerCase(), code as Topic);
}

const errors: string[] = [];
const out: string[] = [];
const ids = new Set<string>();
rows.forEach((r, i) => {
  const line = i + 2;
  const form = Number(col(r, 'form').replace(/^f/i, ''));
  const topic = byName.get(col(r, 'topic').toLowerCase());
  const answer = 'ABCD'.indexOf(col(r, 'answer').toUpperCase());
  const id = `t.${col(r, 'id') || `row${line}`}`.toLowerCase().replace(/[^a-z0-9.]+/g, '-');
  const q = {
    id, form, topic, tier: form <= 3 ? 'junior' : 'dse',
    q: col(r, 'question'),
    options: ['a', 'b', 'c', 'd'].map((k) => col(r, k)),
    answer,
    why: col(r, 'explanation'),
  };
  const bad: string[] = [];
  if (!(form >= 1 && form <= 6)) bad.push('form must be 1-6');
  if (!topic) bad.push(`unknown topic "${col(r, 'topic')}"`);
  else if (topic.startsWith('J') !== form <= 3) bad.push(`topic ${topic} does not match F${form}`);
  if (answer < 0) bad.push('answer must be A, B, C or D');
  if (ids.has(id)) bad.push(`duplicate id ${id}`);
  for (const s of [q.q, ...q.options, q.why]) {
    const missing = [...new Set([...s].filter((ch) => ch !== '\n' && !FONT_CHARS.includes(ch)))];
    if (missing.length) bad.push(`characters the font cannot draw: ${missing.join(' ')}`);
  }
  if (bad.length) { errors.push(`row ${line}: ${[...new Set(bad)].join('; ')}`); return; }
  ids.add(id);
  out.push(`  ${JSON.stringify(q)},`);
});

if (errors.length) {
  console.error(errors.join('\n'));
  console.error(`\n${errors.length} row(s) not imported. Nothing was written.`);
  process.exit(1);
}

writeFileSync(new URL('../src/questions-imported.ts', import.meta.url), `/**
 * GENERATED by scripts/import-questions.ts from ${file.split(/[\\\\/]/).pop()}. Do not edit by hand:
 * edit the CSV and run \`npm run import -- path/to/bank.csv\` again.
 */
import type { Question } from './questions';

export const IMPORTED: Question[] = [
${out.join('\n')}
] as Question[];
`);
console.log(`imported ${out.length} questions. now run: npm run check`);
